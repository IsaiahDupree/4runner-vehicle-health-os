"""Embed the actual local UI as deterministic gzip data for ESP32 flash."""
import gzip
import hashlib
import json
from pathlib import Path


def embed(source, output):
    html = (source / 'index.html').read_text()
    css = (source / 'style.css').read_text()
    js = (source / 'app.mjs').read_text()
    html = html.replace('<link rel="stylesheet" href="./style.css">', '<style>' + css + '</style>')
    html = html.replace('<script type="module" src="./app.mjs"></script>', '<script type="module">' + js + '</script>')
    data = gzip.compress(html.encode(), compresslevel=9, mtime=0)
    rows = [', '.join('0x%02x' % b for b in data[i:i+24]) for i in range(0, len(data), 24)]
    output.write_text('// Generated by embed_ui.py; edit ../ui sources.\n#pragma once\n'
                      '#include <cstdint>\nstatic const uint8_t revgUi[] PROGMEM = {\n' + ',\n'.join(rows) + '\n};\n')
    return {'source_sha256': {name: hashlib.sha256((source/name).read_bytes()).hexdigest()
                             for name in ('index.html','style.css','app.mjs')},
            'html_bytes': len(html.encode()), 'gzip_bytes': len(data),
            'gzip_sha256': hashlib.sha256(data).hexdigest()}


if __name__ == '__main__':
    root = Path(__file__).resolve().parent
    print(json.dumps(embed(root.parent/'ui', root/'revg_ui.h'), indent=2))
